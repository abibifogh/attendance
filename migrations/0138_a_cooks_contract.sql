4. FOOD SAFETY AND HYGIENE

4.1 The Employee shall prepare, cook, hold and store food safely, in
    accordance with the Public Health Act, 2012 (Act 851), the requirements of
    the Food and Drugs Authority and the local assembly, and the Company''s
    food safety procedures.
4.2 Before starting work as a food handler, and thereafter at the intervals
    the law or the Company requires, the Employee shall undergo a medical
    examination and hold a valid food handler''s health certificate. The
    Company shall bear the cost of the examination and the certificate. The
    Employee may not handle food while the certificate has lapsed.
4.3 The Employee shall report to the person in charge, before starting a shift,
    any diarrhoea, vomiting, fever, infected cut or sore, or other condition
    that could contaminate food, and shall not handle food until cleared to do
    so. Time off for such a condition is treated as sick leave under clause 7.
4.4 The Employee shall wear the clean uniform, apron and hair covering
    provided, keep fingernails short and clean, wear no jewellery other than a
    plain band while handling food, wash their hands as the procedures
    require, and shall not smoke, chew gum or eat in food preparation areas.
4.5 The Employee shall keep the records the Company requires, such as
    cleaning schedules, temperature checks and delivery checks, and shall
    record them truthfully.
4.6 The Employee shall know and follow the Company''s procedure for food
    allergies, and shall tell a guest or customer the truth about what a dish
    contains or refer the question to the person in charge.

5. HEALTH AND SAFETY IN THE KITCHEN

5.1 The Company shall provide a safe place of work and safe equipment, as
    required by section 118 of Act 651, together with the protective clothing
    and equipment the work requires, free of charge.
5.2 The Employee shall use knives, slicers, mixers, fryers, ovens, gas and
    other equipment only as trained and instructed, shall use the protective
    clothing and equipment provided, and shall report at once any fault, gas
    smell, spill, injury or near miss.
5.3 The Employee shall take part in fire, first aid and safety training
    provided by the Company and shall know where the fire blanket,
    extinguishers and first aid box are kept.
5.4 The Employee may remove themselves from a work situation they reasonably
    believe presents an imminent and serious danger to their life or health,
    and shall report it at once, as section 118 of Act 651 allows.

