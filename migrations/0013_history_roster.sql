-- The year's rota, from the Hik-Connect schedule export.
--
-- Three thousand two hundred and thirty-six rostered days between 1 January and
-- 16 August 2026, for twenty-three people. Loaded through a staging table and
-- joined on employee number and shift name rather than on ids, because ids here
-- depend on the order earlier migrations happened to insert things in, and a
-- rota keyed to that is a rota that breaks the first time a seed is edited.
--
-- Michael Kesseh appears in the export and is not in this system: no terminal
-- enrolment, no clock records, and rostering somebody the terminal has never
-- seen would produce an unbroken run of absences for them. Left out.
--
-- Where a person's row was scheduled under two positions on one day the export
-- had no such case, so nothing is being silently dropped here.

CREATE TABLE _imp_roster (employee_no TEXT NOT NULL, day TEXT NOT NULL, shift_name TEXT NOT NULL);

